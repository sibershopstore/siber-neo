import AppKit
import ImageIO

struct ShelfItem: Codable, Identifiable, Equatable {
    var id = UUID()
    var path: String

    var url: URL { URL(fileURLWithPath: path) }
    var name: String { url.lastPathComponent }
}

/// The Shelf stores only file location references, never copies.
final class ShelfStore: ObservableObject {
    @Published private(set) var items: [ShelfItem] = []
    @Published private(set) var thumbnails: [String: NSImage] = [:]

    private let fileName = "shelf.json"
    private static let imageExtensions: Set<String> = ["png", "jpg", "jpeg", "heic", "gif", "tiff", "webp", "bmp"]

    init() {
        let stored = Storage.load([ShelfItem].self, from: fileName) ?? []
        items = stored.filter { FileManager.default.fileExists(atPath: $0.path) }
        items.forEach { makeThumbnail(for: $0.path) }
    }

    func add(_ url: URL) {
        guard url.isFileURL, !items.contains(where: { $0.path == url.path }) else { return }
        items.insert(ShelfItem(path: url.path), at: 0)
        makeThumbnail(for: url.path)
        persist()
    }

    /// Small previews for image files, generated in the background with ImageIO.
    private func makeThumbnail(for path: String) {
        let ext = (path as NSString).pathExtension.lowercased()
        guard Self.imageExtensions.contains(ext), thumbnails[path] == nil else { return }
        DispatchQueue.global(qos: .utility).async { [weak self] in
            let url = URL(fileURLWithPath: path) as CFURL
            let options: [CFString: Any] = [
                kCGImageSourceCreateThumbnailFromImageAlways: true,
                kCGImageSourceCreateThumbnailWithTransform: true,
                kCGImageSourceThumbnailMaxPixelSize: 160
            ]
            guard let source = CGImageSourceCreateWithURL(url, nil),
                  let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else { return }
            let thumbnail = NSImage(cgImage: image, size: NSSize(width: image.width, height: image.height))
            DispatchQueue.main.async {
                self?.thumbnails[path] = thumbnail
            }
        }
    }

    func remove(_ id: UUID) {
        items.removeAll { $0.id == id }
        persist()
    }

    func clear() {
        items.removeAll()
        persist()
    }

    private func persist() {
        Storage.save(items, to: fileName)
    }
}

struct ClipItem: Identifiable, Equatable {
    let id = UUID()
    let text: String
    let date: Date
}

/// Text clipboard history. Kept in memory only, never written to disk,
/// and automatically skips entries marked as concealed by password managers.
final class ClipboardStore: ObservableObject {
    static let limit = 20

    @Published private(set) var items: [ClipItem] = []

    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword")
    ]

    init() {
        let timer = Timer(timeInterval: 0.8, repeats: true) { [weak self] _ in
            self?.poll()
        }
        timer.tolerance = 0.3
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func copy(_ item: ClipItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        items.removeAll { $0.id == item.id }
        items.insert(ClipItem(text: item.text, date: Date()), at: 0)
    }

    func clear() {
        items.removeAll()
    }

    private var pollCount = 0

    private func poll() {
        pollCount += 1
        if EnergyMode.shared.shouldSkip(tick: pollCount, factor: 2) { return }
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount

        let types = Set(pasteboard.types ?? [])
        guard types.isDisjoint(with: ignoredTypes),
              let text = pasteboard.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }

        items.removeAll { $0.text == text }
        items.insert(ClipItem(text: text, date: Date()), at: 0)
        if items.count > Self.limit {
            items.removeLast(items.count - Self.limit)
        }
    }
}
